import {spawnSync} from 'node:child_process';
import {readFile,writeFile,mkdir,stat} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';

// Repackage the existing H.264 packets; do not rescale or re-encode either clip.
const configs={hero:['hero-scrub.mp4',.5],story:['dream-story.mp4',1]};
const streams={};
for(const [name,[file,seconds]] of Object.entries(configs)){
 const input=resolve('dist/assets',file);
 const hash=createHash('sha256').update(await readFile(input)).digest('hex').slice(0,12);
 const folder=`streams/${name}-${hash}`,directory=resolve('dist/assets',folder);
 await mkdir(directory,{recursive:true});
 const manifest=resolve(directory,'manifest.mpd');
 try{await stat(manifest);await stat(resolve(directory,'init.mp4'));}catch{
  const result=spawnSync('ffmpeg',['-y','-hide_banner','-loglevel','error','-i',input,'-map','0:v:0','-an','-c:v','copy','-f','dash','-seg_duration',String(seconds),'-use_template','1','-use_timeline','1','-init_seg_name','init.mp4','-media_seg_name','chunk-$Number%03d$.m4s','manifest.mpd'],{stdio:'inherit',cwd:directory});
  if(result.status!==0)throw result.error || Error(`Cannot segment ${name}`);
 }
 const xml=await readFile(manifest,'utf8'),scale=Number(xml.match(/timescale="(\d+)"/)[1]);
 let cursor=0,index=1;const segments=[];
 for(const tag of xml.matchAll(/<S\s+([^>]+)\/>/g)){
  const attrs=Object.fromEntries([...tag[1].matchAll(/(\w+)="([^"]+)"/g)].map(m=>[m[1],Number(m[2])]));
  if(attrs.t!==undefined)cursor=attrs.t;
  for(let repeat=0;repeat<=(attrs.r || 0);repeat++){
   const src=`./assets/${folder}/chunk-${String(index++).padStart(3,'0')}.m4s`;
   segments.push({src,start:cursor/scale,end:(cursor+attrs.d)/scale});cursor+=attrs.d;
  }
 }
 const duration=cursor/scale;
 await writeFile(manifest,xml.replace(/mediaPresentationDuration="[^"]+"/,`mediaPresentationDuration="PT${duration.toFixed(6)}S"`));
 streams[name]={mime:`video/mp4; codecs="${xml.match(/codecs="([^"]+)"/)[1]}"`,duration,init:`./assets/${folder}/init.mp4`,segments};
 console.log(`${name}: ${segments.length} segments, ${duration.toFixed(6)}s; original encoded packets preserved`);
}
await writeFile('src/data/media-streams.js','// Generated by npm run media:segment from the checked-in MP4 files.\nexport const mediaStreams = '+JSON.stringify(streams,null,2)+';\n');
